export type TranslationKey = keyof typeof zh;

export function isTranslationKey(key: string): key is TranslationKey {
  return Object.prototype.hasOwnProperty.call(zh, key);
}

// A key in a given language rather than the interface's: the assistant's
// answer parts follow the language of the question, so a Chinese question
// on the English interface reads all in Chinese.
export function translate(language: SupportedLanguage, key: TranslationKey, variables: Record<string, string | number> = {}) {
  const dictionary = language === "en-US" ? en : zh;
  return Object.entries(variables).reduce((output, [name, replacement]) => output.replaceAll(`{${name}}`, String(replacement)), dictionary[key] || zh[key]);
}

