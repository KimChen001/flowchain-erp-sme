type I18nValue = {
  language: SupportedLanguage;
  locale: SupportedLocale;
  timezone: string;
  workspaceName: string;
  defaultLanguage: SupportedLanguage;
  t: (key: keyof typeof zh, variables?: Record<string, string | number>) => string;
  routeLabel: (route: AppRouteDefinition, module?: boolean) => string;
  formatDateTime: (value: string | Date) => string;
  formatNumber: (value: number) => string;
  refresh: () => Promise<void>;
  setGuestLanguage: (language: SupportedLanguage) => void;
};

// Before a workspace's settings load (or when they cannot), format with the
// product default locale and the browser's own timezone rather than
// assuming China; a loaded workspace always supplies its own values.
const FALLBACK_LOCALE = "en-US";
const FALLBACK_TIMEZONE = (() => {
  try { return Intl.DateTimeFormat().resolvedOptions().timeZone || "UTC"; } catch { return "UTC"; }
})();

const fallback: I18nValue = {
  language: "en-US",
  locale: FALLBACK_LOCALE,
  timezone: FALLBACK_TIMEZONE,
  workspaceName: "",
  defaultLanguage: "en-US",
  t: key => en[key],
  routeLabel: route => route.label,
  formatDateTime: value => new Intl.DateTimeFormat(FALLBACK_LOCALE, { dateStyle: "medium", timeStyle: "short", timeZone: FALLBACK_TIMEZONE }).format(new Date(value)),
  formatNumber: value => new Intl.NumberFormat(FALLBACK_LOCALE).format(value),
  refresh: async () => {},
  setGuestLanguage: () => {},
};

const I18nContext = createContext<I18nValue>(fallback);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [state, setState] = useState<LocalizationPayload>({
    languagePreference: null,
    defaultLanguage: "en-US",
    effectiveLanguage: "en-US",
    locale: FALLBACK_LOCALE,
    timezone: FALLBACK_TIMEZONE,
    workspaceName: "",
  });
  const refresh = useCallback(async () => {
    if (!localStorage.getItem(AUTH_TOKEN_KEY)) {
      const guestLanguage = localStorage.getItem("flowchain:guest-language") === "zh-CN" ? "zh-CN" : "en-US";
      setState({ languagePreference: null, defaultLanguage: "en-US", effectiveLanguage: guestLanguage, locale: FALLBACK_LOCALE, timezone: FALLBACK_TIMEZONE, workspaceName: "" });
      return;
    }
    try {
      setState(await apiJson<LocalizationPayload>("/api/me/localization"));
    } catch {
      setState(current => ({ ...current, effectiveLanguage: current.effectiveLanguage || "en-US" }));
    }
  }, []);
  const setGuestLanguage = useCallback((language: SupportedLanguage) => {
    if (localStorage.getItem(AUTH_TOKEN_KEY)) return;
    localStorage.setItem("flowchain:guest-language", language);
    setState(current => ({ ...current, effectiveLanguage: language }));
  }, []);
  useEffect(() => {
    void refresh();
    const listener = () => void refresh();
    window.addEventListener("flowchain:localization-changed", listener);
    return () => window.removeEventListener("flowchain:localization-changed", listener);
  }, [refresh]);
  useEffect(() => {
    document.documentElement.lang = state.effectiveLanguage;
  }, [state.effectiveLanguage]);
  useEffect(() => { setWorkspaceTimeZone(state.timezone); }, [state.timezone]);
  const value = useMemo<I18nValue>(() => {
    const dictionary = state.effectiveLanguage === "en-US" ? en : zh;
    const t = (key: keyof typeof zh, variables: Record<string, string | number> = {}) =>
      Object.entries(variables).reduce((output, [name, replacement]) => output.replaceAll(`{${name}}`, String(replacement)), dictionary[key] || zh[key]);
    return {
      language: state.effectiveLanguage,
      locale: state.locale,
      timezone: state.timezone,
      workspaceName: state.workspaceName,
      defaultLanguage: state.defaultLanguage,
      t,
      routeLabel: (route, module = false) => {
        const key = routeKeys[module ? route.moduleId : route.id] || routeKeys[route.id];
        return key ? t(key) : workspaceCopy(module ? route.moduleLabel : route.label, state.effectiveLanguage);
      },
      formatDateTime: value => new Intl.DateTimeFormat(state.locale, { dateStyle: "medium", timeStyle: "short", timeZone: state.timezone }).format(new Date(value)),
      formatNumber: value => new Intl.NumberFormat(state.locale).format(value),
      refresh,
      setGuestLanguage,
    };
  }, [refresh, setGuestLanguage, state]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
